def _hash_seed_password(plain: str) -> str:
    """Hash a password using whichever bcrypt-capable helper is available.

    Tries the project's compliance.auth_config first (HIPAA wiring), then
    falls back to passlib directly. Last-resort: store plain — visibly wrong,
    but prevents a NOT NULL crash that would block all seeding.
    """
    try:
        from compliance.auth_config import hash_password as _hp
        return _hp(plain)
    except Exception:
        pass
    try:
        from passlib.context import CryptContext
        return CryptContext(schemes=["bcrypt"], deprecated="auto").hash(plain)
    except Exception:
        logger.warning("Password hashing unavailable; storing seed password in plaintext")
        return plain


