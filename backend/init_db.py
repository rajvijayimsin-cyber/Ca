def _auto_migrate():
    """Add missing columns to existing tables (lightweight ALTER TABLE migration).

    ``Base.metadata.create_all()`` only creates *new* tables — it will NOT add
    columns that were added to a model after the table was first created (e.g.
    when a Docker volume persists between code changes).  This function fills
    that gap by comparing each model's declared columns against the live DB
    schema and issuing ``ALTER TABLE … ADD COLUMN`` for any gaps.
    """
    inspector = sa_inspect(engine)
    existing_tables = set(inspector.get_table_names())

    for table_name, table in Base.metadata.tables.items():
        if table_name not in existing_tables:
            continue  # table doesn't exist yet — create_all handles it

        db_columns = {c["name"] for c in inspector.get_columns(table_name)}

        for col in table.columns:
            if col.name in db_columns:
                continue
            # Determine the SQL type string
            col_type = col.type.compile(dialect=engine.dialect)
            nullable = "NULL" if col.nullable else "NOT NULL"
            default_clause = ""
            if col.server_default is not None:
                default_clause = f" DEFAULT {col.server_default.arg}"
            elif col.nullable:
                default_clause = " DEFAULT NULL"

            ddl = f"ALTER TABLE {table_name} ADD COLUMN {col.name} {col_type} {nullable}{default_clause}"
            try:
                with engine.begin() as conn:
                    conn.execute(sa_text(ddl))
                logger.info(f"Auto-migrated: {table_name}.{col.name} ({col_type})")
            except Exception as e:
                # Column may already exist (race condition) or type may be unsupported
                logger.warning(f"Auto-migrate skipped {table_name}.{col.name}: {e}")


