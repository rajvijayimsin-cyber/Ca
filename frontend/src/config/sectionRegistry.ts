export function buildSectionContext(pageId: string): string {
  const sections = SECTION_REGISTRY[pageId];
  if (!sections) return '';
  return sections.map(s => {
    const parts = [`- "${s.id}" (${s.label}, order: ${s.defaultOrder})`];
    if (s.hasTitle) parts.push(`  title: "${s.defaultTitle || ''}"`);
    if (s.hasGrid) parts.push(`  grid: ${s.defaultGridCols} columns`);
    if (s.description) parts.push(`  ${s.description}`);
    if (s.items) parts.push(`  items: ${s.items.map(i => `"${i.id}" (${i.label})`).join(', ')}`);
    if (s.defaultTexts && Object.keys(s.defaultTexts).length > 0) {
      parts.push(`  text keys: ${Object.entries(s.defaultTexts).map(([k, v]) => `"${k}": "${v}"`).join(', ')}`);
    }
    return parts.join('\n');
  }).join('\n');
}

export function buildAllSectionsContext(): string {
  return Object.keys(SECTION_REGISTRY).map(pageId => {
    return `[${pageId}]\n${buildSectionContext(pageId)}`;
  }).join('\n\n');
}
